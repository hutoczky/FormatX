import r516Production from './production-content-entry-r515.js';

/* FormatX R517 candidate — consolidate only the six contiguous mobile-only
   first-paint stylesheet requests proven by Lighthouse 13.4.1 to sit on the
   mobile render-blocking path. The bundle is generated byte-for-byte from the
   canonical source styles in their existing cascade order. Shared desktop/P0
   first-paint owners, R515 critical-core ownership and MAG runtime are frozen. */

const PUBLIC_HOSTS = new Set(['formatxsuite.com', 'www.formatxsuite.com']);
const MOBILE_BUNDLE_PATH = '/scifi-ui/styles/formatx-mobile-critical-r517.css';
const MOBILE_MEDIA = '(max-width: 900px)';
const MOBILE_BUNDLE_SOURCES = new Set([
  '/scifi-ui/styles/formatx-mobile-reference-layout-v1.css',
  '/scifi-ui/styles/formatx-flow-first-r74.css',
  '/scifi-ui/styles/formatx-responsive-text-guard-r72.css',
  '/scifi-ui/styles/formatx-mobile-proof-controls-r204.css',
  '/scifi-ui/styles/formatx-mobile-layout-r207.css',
  '/scifi-ui/styles/formatx-native-orb-reference-r250.css',
]);

function isSafeMethod(request) {
  return request.method === 'GET' || request.method === 'HEAD';
}

function stylesheetPath(tag) {
  const hrefMatch = tag.match(/\bhref=(["'])(.*?)\1/i);
  if (!hrefMatch) return '';
  try {
    return new URL(hrefMatch[2], 'https://formatxsuite.com/scifi-ui/').pathname;
  } catch (_) {
    return '';
  }
}

function consolidateMobileFirstPaintRequests(html) {
  let inserted = false;
  return String(html || '').replace(/<link\b[^>]*\brel=["']stylesheet["'][^>]*>/gi, tag => {
    const pathname = stylesheetPath(tag);
    if (!MOBILE_BUNDLE_SOURCES.has(pathname)) return tag;
    if (inserted) return '';
    inserted = true;
    return `<link rel="stylesheet" fetchpriority="high" media="${MOBILE_MEDIA}" data-fx-mobile-critical-r517="true" href="${MOBILE_BUNDLE_PATH}?v=20260904-r517-cascade-consolidation">`;
  });
}

function r517Headers(source) {
  const headers = new Headers(source);
  headers.set('X-FormatX-Mobile-Critical', 'r517-cascade-consolidation');
  return headers;
}

export default {
  async fetch(request, env, ctx) {
    const response = await r516Production.fetch(request, env, ctx);
    const url = new URL(request.url);
    if (!isSafeMethod(request) || !PUBLIC_HOSTS.has(url.hostname)) return response;

    const headers = r517Headers(response.headers);
    if (request.method === 'HEAD') {
      headers.delete('Content-Length');
      return new Response(null, { status: response.status, statusText: response.statusText, headers });
    }

    const contentType = headers.get('Content-Type') || '';
    if (!contentType.includes('text/html')) {
      return new Response(response.body, { status: response.status, statusText: response.statusText, headers });
    }

    const html = consolidateMobileFirstPaintRequests(await response.text());
    headers.delete('Content-Length');
    headers.delete('Content-Encoding');
    headers.delete('ETag');
    headers.set('Cache-Control', 'no-store, max-age=0');
    return new Response(html, { status: response.status, statusText: response.statusText, headers });
  },
};
